<#
  IntuneAppFastDeploy - software removal script.

  Generated by the tool: do not edit by hand, publish again from the tool instead.
  Runs on Windows PowerShell 5.1 (the version the Intune Management Extension uses).

  Modes
    Detect             Intune Win32 detection rule: writes a line when the software is
                       present, writes nothing when it is absent. Always exits 0.
    Requirement        Intune Win32 requirement rule: writes "present" or "absent".
    RemediationDetect  Remediation detection script: exits 1 when the software is
                       present (a remediation is needed), 0 when it is absent.
    Uninstall          Removes the software. Exits 0 when nothing is left, 3010 when
                       a restart is needed, 1 when something could not be removed.
    Library            Defines the functions and does nothing (used by the tests).

  Only software whose display name is exactly one of the configured names is touched.
#>
param(
    [ValidateSet('Detect', 'Requirement', 'RemediationDetect', 'Uninstall', 'Library')]
    [string]$Mode = '@@MODE@@'
)

$ErrorActionPreference = 'Stop'

# The Intune agent starts commands from a 32-bit process. On 64-bit Windows, start
# again in 64-bit PowerShell: some Windows commands (Store packages) only work there.
if ($Mode -ne 'Library' -and $env:PROCESSOR_ARCHITEW6432 -and $PSCommandPath) {
    $native = Join-Path $env:SystemRoot 'sysnative\WindowsPowerShell\v1.0\powershell.exe'
    if (Test-Path -LiteralPath $native) {
        & $native -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $PSCommandPath -Mode $Mode
        exit $LASTEXITCODE
    }
}

# Settings chosen in the tool, as base64-encoded JSON: data, never code.
$ConfigBase64 = '@@CONFIG@@'
$Config = [System.Text.Encoding]::UTF8.GetString([System.Convert]::FromBase64String($ConfigBase64)) | ConvertFrom-Json

$UninstallKeyPath = 'SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'
$script:LogFile = $null

function Write-Log {
    param([string]$Message)
    try {
        if ($null -eq $script:LogFile) {
            $folder = Join-Path $env:ProgramData 'Microsoft\IntuneManagementExtension\Logs'
            $name = 'IAFD-Remove-' + ([string]$Config.slug) + '.log'
            $candidate = Join-Path $folder $name
            try {
                if (-not (Test-Path -LiteralPath $folder)) { throw 'no Intune log folder' }
                Add-Content -LiteralPath $candidate -Value '' -ErrorAction Stop
            }
            catch {
                # Not an Intune device, or a standard user: fall back to the temp folder.
                $candidate = Join-Path $env:TEMP $name
            }
            $script:LogFile = $candidate
        }
        $bits = [System.IntPtr]::Size * 8
        $line = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss') + ' [' + $Mode + ', ' + $bits + '-bit] ' + $Message
        Add-Content -LiteralPath $script:LogFile -Value $line -ErrorAction Stop
    }
    catch {
        # Logging must never make the script fail.
        $null = $_
    }
}

function ConvertTo-ComparableVersion {
    # "8.0.2010.9" -> [version]; returns $null when the text does not start with a number.
    param([string]$Text)
    if ($Text -match '^\s*(\d+(?:\.\d+){0,3})') {
        $number = $Matches[1]
        if ($number -notmatch '\.') { $number = $number + '.0' }
        try { return [version]$number } catch { return $null }
    }
    return $null
}

function Test-VersionWanted {
    # Does this installed version fall under the rule chosen in the tool?
    param([string]$Version)
    $rule = $Config.versions
    if ($null -eq $rule -or $rule.mode -eq 'any') { return $true }
    if ($rule.mode -eq 'list') { return (@($rule.values) -contains $Version) }
    if ($rule.mode -eq 'below') {
        $installed = ConvertTo-ComparableVersion -Text $Version
        $limit = ConvertTo-ComparableVersion -Text ([string]$rule.value)
        # A version that cannot be compared is left alone.
        if ($null -eq $installed -or $null -eq $limit) { return $false }
        return ($installed -lt $limit)
    }
    return $false
}

function Get-RegistryRoots {
    if ($Config.kind -eq 'user') {
        return @(@{ Hive = [Microsoft.Win32.RegistryHive]::CurrentUser; View = [Microsoft.Win32.RegistryView]::Default })
    }
    # The Intune agent is a 32-bit process: open both views explicitly instead of
    # relying on which one the current process sees.
    return @(
        @{ Hive = [Microsoft.Win32.RegistryHive]::LocalMachine; View = [Microsoft.Win32.RegistryView]::Registry64 },
        @{ Hive = [Microsoft.Win32.RegistryHive]::LocalMachine; View = [Microsoft.Win32.RegistryView]::Registry32 }
    )
}

function Get-RegistrySoftware {
    # Entries of "Programs and features" whose name is exactly one of the configured names.
    $found = @()
    $seen = @{}
    foreach ($root in (Get-RegistryRoots)) {
        $base = [Microsoft.Win32.RegistryKey]::OpenBaseKey($root.Hive, $root.View)
        try {
            $uninstall = $base.OpenSubKey($UninstallKeyPath)
            if ($null -eq $uninstall) { continue }
            foreach ($keyName in $uninstall.GetSubKeyNames()) {
                $entry = $uninstall.OpenSubKey($keyName)
                if ($null -eq $entry) { continue }
                try {
                    $name = [string]$entry.GetValue('DisplayName')
                    if ([string]::IsNullOrWhiteSpace($name)) { continue }
                    # -contains compares whole strings, ignoring case: an exact match only.
                    if (-not (@($Config.names) -contains $name.Trim())) { continue }
                    $version = [string]$entry.GetValue('DisplayVersion')
                    if (-not (Test-VersionWanted -Version $version)) { continue }
                    $uninstallString = [string]$entry.GetValue('UninstallString')
                    $identity = ($keyName + '|' + $uninstallString).ToLowerInvariant()
                    if ($seen.ContainsKey($identity)) { continue }   # same key seen in both views (32-bit Windows)
                    $seen[$identity] = $true
                    $found += [pscustomobject]@{
                        Name                 = $name.Trim()
                        Version              = $version
                        KeyName              = $keyName
                        Hive                 = $root.Hive
                        View                 = $root.View
                        UninstallString      = $uninstallString
                        QuietUninstallString = [string]$entry.GetValue('QuietUninstallString')
                        InstallLocation      = [string]$entry.GetValue('InstallLocation')
                        WindowsInstaller     = [string]$entry.GetValue('WindowsInstaller')
                    }
                }
                finally { $entry.Close() }
            }
            $uninstall.Close()
        }
        finally { $base.Close() }
    }
    return , $found
}

function Get-StoreSoftware {
    $found = @()
    foreach ($package in @(Get-AppxPackage -AllUsers)) {
        if (-not (@($Config.names) -contains [string]$package.Name)) { continue }
        if (-not (Test-VersionWanted -Version ([string]$package.Version))) { continue }
        $found += [pscustomobject]@{
            Name            = [string]$package.Name
            Version         = [string]$package.Version
            PackageFullName = [string]$package.PackageFullName
        }
    }
    return , $found
}

function Get-TargetSoftware {
    if ($Config.kind -eq 'store') { return , (Get-StoreSoftware) }
    return , (Get-RegistrySoftware)
}

function Test-EntryPresent {
    param($Entry)
    $base = [Microsoft.Win32.RegistryKey]::OpenBaseKey($Entry.Hive, $Entry.View)
    try {
        $key = $base.OpenSubKey($UninstallKeyPath + '\' + $Entry.KeyName)
        if ($null -eq $key) { return $false }
        $key.Close()
        return $true
    }
    finally { $base.Close() }
}

function Get-UninstallPlan {
    # How to remove one entry silently, or $null when no silent method is known.
    param($Entry)
    $productCode = $null
    $looksLikeMsi = ($Entry.WindowsInstaller -eq '1') -or ($Entry.UninstallString -match '(?i)msiexec')
    if ($looksLikeMsi -and $Entry.KeyName -match '^\{[0-9A-Fa-f]{8}(-[0-9A-Fa-f]{4}){3}-[0-9A-Fa-f]{12}\}$') {
        $productCode = $Entry.KeyName
    }
    elseif ($Entry.UninstallString -match '(?i)msiexec.*?(\{[0-9A-Fa-f]{8}(?:-[0-9A-Fa-f]{4}){3}-[0-9A-Fa-f]{12}\})') {
        $productCode = $Matches[1]
    }
    if ($productCode) {
        return [pscustomobject]@{
            Method = 'msi'
            File   = (Join-Path $env:SystemRoot 'System32\msiexec.exe')
            Line   = '/x ' + $productCode + ' /qn /norestart'
        }
    }
    $command = [string]$Config.command
    if (-not [string]::IsNullOrWhiteSpace($command)) {
        $line = $command.Replace('{UninstallString}', $Entry.UninstallString).Replace('{InstallLocation}', $Entry.InstallLocation)
        return [pscustomobject]@{ Method = 'command'; File = $null; Line = $line }
    }
    if (-not [string]::IsNullOrWhiteSpace($Entry.QuietUninstallString)) {
        return [pscustomobject]@{ Method = 'quiet'; File = $null; Line = $Entry.QuietUninstallString }
    }
    return $null
}

function Invoke-Plan {
    # Runs the command and returns its exit code, or $null when it had to be stopped.
    param($Plan)
    $seconds = [int]$Config.timeout_seconds
    if ($seconds -le 0) { $seconds = 1800 }
    if ($Plan.File) {
        $process = Start-Process -FilePath $Plan.File -ArgumentList $Plan.Line -PassThru -WindowStyle Hidden
    }
    else {
        # cmd /s /c "<line>" runs the line exactly as written, quotes included.
        $arguments = '/d /s /c "' + $Plan.Line + '"'
        $process = Start-Process -FilePath (Join-Path $env:SystemRoot 'System32\cmd.exe') -ArgumentList $arguments -PassThru -WindowStyle Hidden
    }
    # Reading the handle now is what makes ExitCode available once the process has ended.
    $null = $process.Handle
    if (-not $process.WaitForExit($seconds * 1000)) {
        Write-Log ('Timed out after ' + $seconds + ' s, stopping process ' + $process.Id)
        & (Join-Path $env:SystemRoot 'System32\taskkill.exe') /T /F /PID $process.Id 2>&1 | Out-Null
        return $null
    }
    return $process.ExitCode
}

function Wait-EntryGone {
    # Some uninstallers return before they have finished: give them time.
    param($Entry)
    $seconds = [int]$Config.settle_seconds
    if ($seconds -le 0) { $seconds = 120 }
    $deadline = (Get-Date).AddSeconds($seconds)
    while ($true) {
        if (-not (Test-EntryPresent -Entry $Entry)) { return $true }
        if ((Get-Date) -ge $deadline) { return $false }
        Start-Sleep -Seconds 2
    }
}

function Remove-RegistrySoftware {
    param($Entries)
    $failed = 0
    $restart = $false
    foreach ($entry in $Entries) {
        $label = $entry.Name + ' ' + $entry.Version
        $plan = Get-UninstallPlan -Entry $entry
        if ($null -eq $plan) {
            Write-Log ($label + ': no silent uninstall method. Uninstall string: ' + $entry.UninstallString)
            Write-Output ($label + ': no silent uninstall method, a command is needed')
            $failed++
            continue
        }
        Write-Log ($label + ': ' + $plan.Method + ' -> ' + $plan.File + ' ' + $plan.Line)
        $code = Invoke-Plan -Plan $plan
        Write-Log ($label + ': exit code ' + $code)
        if ($code -eq 3010 -or $code -eq 1641) { $restart = $true }
        if (Wait-EntryGone -Entry $entry) {
            Write-Output ($label + ': removed')
        }
        else {
            Write-Log ($label + ': still present after the uninstaller ended')
            Write-Output ($label + ': still present (exit code ' + $code + ')')
            $failed++
        }
    }
    if ($failed -gt 0) { return 1 }
    if ($restart) { return 3010 }
    return 0
}

function Remove-StoreSoftware {
    param($Entries)
    $failed = 0
    foreach ($entry in $Entries) {
        try {
            Remove-AppxPackage -Package $entry.PackageFullName -AllUsers -ErrorAction Stop
            Write-Log ($entry.PackageFullName + ': removed')
            Write-Output ($entry.Name + ' ' + $entry.Version + ': removed')
        }
        catch {
            Write-Log ($entry.PackageFullName + ': ' + $_.Exception.Message)
            Write-Output ($entry.Name + ': ' + $_.Exception.Message)
            $failed++
        }
    }
    # Also remove the copy kept for future user profiles.
    try {
        foreach ($provisioned in @(Get-AppxProvisionedPackage -Online)) {
            if (@($Config.names) -contains [string]$provisioned.DisplayName) {
                Remove-AppxProvisionedPackage -Online -PackageName $provisioned.PackageName -ErrorAction Stop | Out-Null
                Write-Log ($provisioned.PackageName + ': provisioned package removed')
            }
        }
    }
    catch {
        Write-Log ('Provisioned packages: ' + $_.Exception.Message)
    }
    if ($failed -gt 0) { return 1 }
    return 0
}

function Invoke-Main {
    $entries = Get-TargetSoftware
    $summary = @($entries | ForEach-Object { $_.Name + ' ' + $_.Version }) -join '; '
    switch ($Mode) {
        'Detect' {
            if ($entries.Count -gt 0) { Write-Output ('Found: ' + $summary) }
            return 0
        }
        'Requirement' {
            if ($entries.Count -gt 0) { Write-Output 'present' } else { Write-Output 'absent' }
            return 0
        }
        'RemediationDetect' {
            if ($entries.Count -gt 0) {
                Write-Output ('Found: ' + $summary)
                return 1
            }
            Write-Output 'Not found'
            return 0
        }
        'Uninstall' {
            if ($entries.Count -eq 0) {
                Write-Log 'Nothing to remove'
                Write-Output 'Nothing to remove'
                return 0
            }
            Write-Log ('To remove: ' + $summary)
            if ($Config.kind -eq 'store') { return (Remove-StoreSoftware -Entries $entries) }
            return (Remove-RegistrySoftware -Entries $entries)
        }
    }
    return 0
}

if ($Mode -ne 'Library') {
    $exitCode = 1
    try {
        # Text goes to standard output, the last value is the exit code.
        $result = @(Invoke-Main)
        $exitCode = [int]$result[-1]
        if ($result.Count -gt 1) { $result[0..($result.Count - 2)] | ForEach-Object { Write-Output $_ } }
    }
    catch {
        Write-Log ('Error: ' + $_.Exception.Message)
        Write-Output ('Error: ' + $_.Exception.Message)
        if ($Mode -eq 'Detect' -or $Mode -eq 'Requirement') { $exitCode = 0 } else { $exitCode = 1 }
    }
    exit $exitCode
}
