<#
  IntuneAppFastDeploy - replaces an older version of a program.

  Generated by the tool: do not edit by hand, publish again from the tool instead.
  Used as the install command of an Intune Win32 application, for programs whose
  installer does not upgrade over an existing version:

    1. removes the older version with the removal script shipped next to this file;
    2. only if that worked, runs the real install command and returns its exit code.

  If the older version cannot be removed, nothing is installed over it.
#>
$ErrorActionPreference = 'Stop'

# Settings chosen in the tool, as base64-encoded JSON: data, never code.
$ConfigBase64 = '@@CONFIG@@'
$Config = [System.Text.Encoding]::UTF8.GetString([System.Convert]::FromBase64String($ConfigBase64)) | ConvertFrom-Json

$here = Split-Path -Parent $PSCommandPath
Set-Location -LiteralPath $here

$powershell = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$removal = Join-Path $here ([string]$Config.remove_script)
$output = & $powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $removal -Mode Uninstall
$removalCode = $LASTEXITCODE
$output | ForEach-Object { Write-Output $_ }
if ($removalCode -ne 0 -and $removalCode -ne 3010) {
    Write-Output 'The older version could not be removed: the new version is not installed.'
    exit $removalCode
}

# cmd /s /c "<line>" runs the install command exactly as it was written in the tool.
$arguments = '/d /s /c "' + [string]$Config.install_command + '"'
$process = Start-Process -FilePath (Join-Path $env:SystemRoot 'System32\cmd.exe') -ArgumentList $arguments -WorkingDirectory $here -PassThru -WindowStyle Hidden
$null = $process.Handle
$process.WaitForExit()
$installCode = $process.ExitCode

# A restart asked by the removal must not be lost when the install itself asks for none.
if ($installCode -eq 0 -and $removalCode -eq 3010) { exit 3010 }
exit $installCode
